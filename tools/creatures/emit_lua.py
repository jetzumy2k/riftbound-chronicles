"""
Writes src/shared/Animation/CreatureMeshes.luau: the skeleton data of the
sculpted creatures (authoring aid, not shipped; PLAN.md D-52). Called by
tools/creatures/build.py.
"""
import math, os
import numpy as np

# Step-cycle phase offsets (walk, run, trot) by leg.
QUAD_PHASES = {"LegFL": (0, 0, 0), "LegFR": (0.5, 0.12, 0.5), "LegBL": (0.75, 0.55, 0.5), "LegBR": (0.25, 0.65, 0)}
SPRAWL_PHASES = {"LegFL": (0, 0, 0), "LegBR": (0, 0, 0), "LegFR": (0.5, 0.5, 0.5), "LegBL": (0.5, 0.5, 0.5)}
GAITS = {"Quadruped": ("Predator", "Heavy"), "Sprawler": ("Heavy", "Heavy"), "Serpent": (None, None)}

HEADER = '''--!strict
--[[
	CreatureMeshes — skeleton data of the sculpted creature meshes
	(GENERATED by tools/creatures/build.py from the same sculpt as the
	meshes; do not edit by hand. PLAN.md D-52).

	Per shape (studs at size 1; "root space" is centred on the Body bone,
	which the creature's HumanoidRootPart sits on, facing -Z):
	  bodyPlan   how it moves (Quadruped / Sprawler / Serpent)
	  gait       CreatureRigs gait (heavyGait for giant sizes)
	  height     Body bone's height above the ground
	  heads      head tags (bones Neck<tag>, Head<tag>, Jaw<tag>)
	  tail       tail bones, base first; segments: a serpent's body bones
	  legs       three-bone legs (CreatureRigs.Leg fields, hip in root
	             space; `parent` is the bone the leg hangs from, `rest` its
	             bind angles in radians)
	The imported models (Studio: File > Import 3D of
	build/creatures/<Name>.gltf, saved as src/server/CreatureModels/<Name>.rbxm)
	carry the bones.
]]

export type MeshLeg = {
	name: string,
	parent: string,
	hip: Vector3,
	reach: Vector2,
	splay: number,
	lengths: { number },
	widths: { number },
	bend: number,
	footAngle: number,
	rest: Vector3,
	walk: number,
	run: number,
	trot: number,
	front: boolean,
	side: number,
}

export type Shape = {
	bodyPlan: string,
	gait: string?,
	heavyGait: string?,
	height: number,
	heads: { string },
	tail: { string },
	segments: { string },
	legs: { MeshLeg },
}

local CreatureMeshes = {}

CreatureMeshes.Shapes = {
'''

FOOTER = '''} :: { [string]: Shape }

return CreatureMeshes
'''


def num(x):
    x = float(x)
    if abs(x) < 1e-9:
        return "0"
    return f"{x:.4f}".rstrip("0").rstrip(".")


def v3(v):
    return f"Vector3.new({num(v[0])}, {num(v[1])}, {num(v[2])})"


def strings(items):
    return "{ " + ", ".join(f'"{s}"' for s in items) + " }" if items else "{}"


def shape(name, creature, meta):
    sk = creature.skeleton
    body = sk["Body"].pos
    gait, heavy = GAITS[meta["plan"]]
    out = [f"\t{name} = {{"]
    out.append(f'\t\tbodyPlan = "{meta["plan"]}",')
    out.append(f'\t\tgait = {"nil" if gait is None else chr(34) + gait + chr(34)},')
    out.append(f'\t\theavyGait = {"nil" if heavy is None else chr(34) + heavy + chr(34)},')
    out.append(f"\t\theight = {num(body[1])},")
    out.append(f"\t\theads = {strings(meta.get('heads', []))},")
    out.append(f"\t\ttail = {strings(meta.get('tail', []))},")
    out.append(f"\t\tsegments = {strings(meta.get('segments', []))},")
    out.append("\t\tlegs = {")
    phases = SPRAWL_PHASES if meta["plan"] == "Sprawler" else QUAD_PHASES
    for leg, (pts, angles, bend, splay) in meta.get("legs", {}).items():
        pts = [np.asarray(q, float) for q in pts]
        lengths = [float(np.linalg.norm(pts[k + 1] - pts[k])) for k in range(3)]
        hip = pts[0] - body
        reach = pts[3] - pts[0]
        walk, run, trot = phases.get(leg, (0, 0, 0))
        out += [
            "\t\t\t{",
            f'\t\t\t\tname = "{leg}",',
            f'\t\t\t\tparent = "{sk[leg].parent.name}",',
            f"\t\t\t\thip = {v3(hip)},",
            f"\t\t\t\treach = Vector2.new({num(reach[0])}, {num(reach[2])}),",
            f"\t\t\t\tsplay = {num(math.degrees(splay))},",
            "\t\t\t\tlengths = { " + ", ".join(num(x) for x in lengths) + " },",
            "\t\t\t\twidths = { 0, 0, 0 },",
            f"\t\t\t\tbend = {bend},",
            f"\t\t\t\tfootAngle = {num(math.degrees(sum(angles)))},",
            "\t\t\t\trest = Vector3.new(" + ", ".join(num(a) for a in angles) + "),",
            f"\t\t\t\twalk = {walk},",
            f"\t\t\t\trun = {run},",
            f"\t\t\t\ttrot = {trot},",
            f"\t\t\t\tfront = {'true' if leg.startswith('LegF') else 'false'},",
            f"\t\t\t\tside = {-1 if leg.endswith('L') else 1},",
            "\t\t\t},",
        ]
    out.append("\t\t},")
    out.append("\t},")
    return "\n".join(out)


def write(root, shapes):
    path = os.path.join(root, "src", "shared", "Animation", "CreatureMeshes.luau")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + "\n".join(shapes) + "\n" + FOOTER)
    return path
